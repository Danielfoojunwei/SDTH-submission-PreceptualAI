#!/usr/bin/env python3
"""Provision a multi-node fleet: node keys, a signed roster, and per-node config.

Every cross-node capability in this repository — corroborated sensing, emitter
localisation, cohort clustering, federated statistics, quorum renewal — needs
two things that no shipped tool produced: a keypair on each node, and an
operator-signed roster naming every node and carrying its public key.

Building that roster by hand means pasting PEM blocks into JSON, once per node,
without transposing one. That friction is the reason the fabric has only ever
been exercised in software, and "no cross-node result on physically separate
hardware" is the largest evidential gap this repository admits to. A deployment
step that is tedious enough to skip is a deployment step that gets skipped.

The operator private key stays on the operator machine. Node private keys are
written per node, 0600, and are meant to be copied to their node and deleted
here. Nothing generated by this tool is evidence of anything measured: it
provisions identity, and identity is all it provisions.

    python3 scripts/provision_fleet.py \\
        --node kval-node-01 --node kval-node-02 \\
        --operator-private-key operator.private.pem \\
        --operator-public-key operator.public.pem \\
        --generate-operator-key \\
        --output-dir fleet/

Positions are optional and operator-declared. They live in the signed roster
rather than in a node's own report on purpose: a self-reported position is a
spoofing surface, and a node that could claim to be anywhere could drag every
emitter estimate with it.
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import timedelta
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from kval_node.capabilities import ROSTER_DOCUMENT_TYPE  # noqa: E402
from kval_node.roster import PeerRoster  # noqa: E402
from kval_node.models import utc_now  # noqa: E402
from kval_node.signing import (  # noqa: E402
    generate_operator_keypair,
    load_private_key,
    public_key_id,
    sign_document,
)

#: Long enough that a demonstration or a field trial does not expire mid-run,
#: short enough that a roster left behind stops working. A roster is a
#: revocation surface: every node it names is one this fleet will believe.
DEFAULT_ROSTER_DAYS = 30

VALID_ROLES = ("node", "sub-node")


def _node_key_paths(output_dir: Path, node_id: str) -> tuple[Path, Path]:
    node_dir = output_dir / node_id
    return node_dir / "node.private.pem", node_dir / "node.public.pem"


def _parse_position(raw: str | None, node_id: str) -> dict[str, float] | None:
    """``lat,lon`` or ``lat,lon,alt``; absent means this node has no position.

    A node without a declared position still corroborates spectrum reports. It
    simply cannot contribute to localisation, which is the honest consequence of
    not knowing where it is — better than a default that would place the whole
    fleet at the same point.
    """
    if raw is None:
        return None
    parts = [item.strip() for item in raw.split(",")]
    if len(parts) not in (2, 3):
        raise ValueError(f"position for {node_id} must be 'lat,lon' or 'lat,lon,alt', got {raw!r}")
    try:
        values = [float(part) for part in parts]
    except ValueError as exc:
        raise ValueError(f"position for {node_id} is not numeric: {raw!r}") from exc
    position = {"latitude_deg": values[0], "longitude_deg": values[1]}
    if len(values) == 3:
        position["altitude_m"] = values[2]
    return position


def build_roster_body(
    node_ids: list[str],
    public_pems: dict[str, str],
    *,
    roster_id: str,
    roles: dict[str, str],
    positions: dict[str, dict[str, float] | None],
    valid_days: int,
) -> dict[str, object]:
    created_at = utc_now()
    peers: list[dict[str, object]] = []
    for node_id in node_ids:
        peer: dict[str, object] = {
            "node_id": node_id,
            "role": roles.get(node_id, "node"),
            "public_key_pem": public_pems[node_id],
        }
        position = positions.get(node_id)
        if position is not None:
            peer["position"] = position
        peers.append(peer)
    return {
        "roster_id": roster_id,
        "created_at": created_at.isoformat(),
        "expires_at": (created_at + timedelta(days=valid_days)).isoformat(),
        "peers": peers,
    }


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Generate node keys and an operator-signed peer roster",
    )
    parser.add_argument(
        "--node", action="append", required=True, metavar="NODE_ID",
        help="node ID; repeat once per node in the fleet",
    )
    parser.add_argument(
        "--position", action="append", default=[], metavar="NODE_ID=lat,lon[,alt]",
        help="operator-surveyed position for a node; repeatable, optional",
    )
    parser.add_argument(
        "--role", action="append", default=[], metavar="NODE_ID=ROLE",
        help=f"role for a node, one of {VALID_ROLES}; defaults to 'node'",
    )
    parser.add_argument("--operator-private-key", type=Path, required=True)
    parser.add_argument("--operator-public-key", type=Path, required=True)
    parser.add_argument("--generate-operator-key", action="store_true")
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--roster-id", default=None, help="defaults to fleet-<timestamp>")
    parser.add_argument("--valid-days", type=int, default=DEFAULT_ROSTER_DAYS)
    return parser


def _parse_assignments(items: list[str], flag: str) -> dict[str, str]:
    parsed: dict[str, str] = {}
    for item in items:
        if "=" not in item:
            raise ValueError(f"{flag} expects NODE_ID=VALUE, got {item!r}")
        node_id, _, value = item.partition("=")
        parsed[node_id.strip()] = value.strip()
    return parsed


def main() -> int:
    args = build_parser().parse_args()
    node_ids = [node.strip() for node in args.node]

    if len(node_ids) != len(set(node_ids)):
        raise SystemExit("duplicate node IDs: every node in a roster must be distinct")
    if len(node_ids) < 2:
        # One node is not a fleet, and a roster of one cannot corroborate
        # anything: the quorum it would need is itself.
        raise SystemExit("a fleet needs at least two nodes; provisioning one proves nothing")

    roles = _parse_assignments(args.role, "--role")
    for node_id, role in roles.items():
        if node_id not in node_ids:
            raise SystemExit(f"--role names {node_id!r}, which is not in the fleet")
        if role not in VALID_ROLES:
            raise SystemExit(f"role {role!r} must be one of {VALID_ROLES}")

    raw_positions = _parse_assignments(args.position, "--position")
    for node_id in raw_positions:
        if node_id not in node_ids:
            raise SystemExit(f"--position names {node_id!r}, which is not in the fleet")
    positions = {
        node_id: _parse_position(raw_positions.get(node_id), node_id) for node_id in node_ids
    }

    output_dir: Path = args.output_dir
    roster_path = output_dir / "peer-roster.signed.json"
    if roster_path.exists():
        raise SystemExit(f"refusing to overwrite an existing roster: {roster_path}")

    if args.generate_operator_key:
        args.operator_private_key.parent.mkdir(parents=True, exist_ok=True)
        args.operator_public_key.parent.mkdir(parents=True, exist_ok=True)
        generate_operator_keypair(args.operator_private_key, args.operator_public_key)

    # Generate every node key before signing anything. A roster missing a node
    # because generation failed halfway is worse than no roster: the fleet would
    # come up, work, and silently exclude that node's reports.
    public_pems: dict[str, str] = {}
    for node_id in node_ids:
        private_path, public_path = _node_key_paths(output_dir, node_id)
        private_path.parent.mkdir(parents=True, exist_ok=True)
        generate_operator_keypair(private_path, public_path)
        public_pems[node_id] = public_path.read_text(encoding="utf-8")

    roster_id = args.roster_id or f"fleet-{utc_now().strftime('%Y%m%dT%H%M%SZ')}"
    body = build_roster_body(
        node_ids, public_pems,
        roster_id=roster_id, roles=roles, positions=positions, valid_days=args.valid_days,
    )

    # Parse it back through the node's own validator before signing, so a roster
    # that the fleet would reject never receives a signature.
    PeerRoster.from_dict(body)

    operator_key = load_private_key(args.operator_private_key)
    envelope = sign_document(ROSTER_DOCUMENT_TYPE, body, operator_key)
    roster_path.write_text(json.dumps(envelope, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    for node_id in node_ids:
        inbox = output_dir / node_id / "inbox"
        inbox.mkdir(parents=True, exist_ok=True)

    print(json.dumps({
        "roster_id": roster_id,
        "roster": str(roster_path),
        "operator_key_id": public_key_id(operator_key.public_key()),
        "nodes": [
            {
                "node_id": node_id,
                "private_key": str(_node_key_paths(output_dir, node_id)[0]),
                "public_key": str(_node_key_paths(output_dir, node_id)[1]),
                "inbox": str(output_dir / node_id / "inbox"),
                "positioned": positions[node_id] is not None,
            }
            for node_id in node_ids
        ],
        "next": "copy each node directory to its node, then delete the private keys here",
    }, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
